export const charName = (key) => CHARACTERS.find((c) => c.key === key)?.name ?? key;

// 好きな贈物を獲得EXPの高い順に返す
export function favoriteGifts(char) {
  return (char?.gifts ?? [])
    .map(([i, rate]) => {
      const g = GIFTS[i];
      const mult = GIFT_EXP[rate];
      return { ...g, rate, mult, total: g.exp * mult };
    })
    .sort((a, b) => b.total - a.total || a.sprite - b.sprite);
}
